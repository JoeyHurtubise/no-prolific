  //Source: https://stackoverflow.com/questions/2450954/how-to-randomize-shuffle-a-javascript-array
  function shuffle(array) {
    var currentIndex = array.length, randomIndex;
  
    // While there remain elements to shuffle...
    while (0 !== currentIndex) {
  
        // Pick a remaining element...
        randomIndex = Math.floor(Math.random() * currentIndex);
        currentIndex--;
  
        // And swap it with the current element.
        [array[currentIndex], array[randomIndex]] = [
            array[randomIndex], array[currentIndex]];
    }
  
    return array;
  };
  
  //Function that creates an array containing given emotion plus 3 randomly-chosen distractors
  function emotion_array(target_emn) {
      var target_emn = target_emn.charAt(0).toUpperCase() + target_emn.slice(1);
      var target_ind = emotions.indexOf(target_emn);
      //find random indeces for 3 distractors
      var a = parseInt(Math.floor(Math.random() * 93), 10);
      var b = parseInt(Math.floor(Math.random() * 93), 10);
      var c = parseInt(Math.floor(Math.random() * 93), 10);
      var inds = [a, b, c];
  
      while (a == target_ind || emotion_syns[target_emn].includes(emotions[a])) {
          a = parseInt(Math.floor(Math.random() * 93), 10);
          inds[0] = a;
      }
  
      while (b == a || b == target_ind || emotion_syns[target_emn].includes(emotions[b]) || emotion_syns[emotions[a]].includes(emotions[b])) {
          b = parseInt(Math.floor(Math.random() * 93), 10);
          inds[1] = b;
      }
      while (c == a || c == b || c == target_ind || emotion_syns[target_emn].includes(emotions[c]) || emotion_syns[emotions[a]].includes(emotions[c]) || emotion_syns[emotions[b]].includes(emotions[c])) {
          c = parseInt(Math.floor(Math.random() * 93), 10);
          inds[2] = c;
      }
      //fill in array according to indeces
      var arr = [target_emn];
      for (var i = 0; i < 3; i++) {
          arr.push(emotions[inds[i]]);
      }
      return shuffle(arr);
  }